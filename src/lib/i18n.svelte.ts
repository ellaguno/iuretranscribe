export const dictionaries: Record<Lang, Record<Key, string>> = { en, es };

/** Idioma actual (reactivo). Lo fija `setLang` con el valor resuelto por el backend. */
export const i18n = $state({ lang: "en" as Lang });

export function setLang(lang: string) {
  i18n.lang = lang === "es" ? "es" : "en";
  document.documentElement.lang = i18n.lang;
}

/** Locale para fechas y números (`toLocale*` / `Intl`). */
export function locale(): string {
  return i18n.lang === "es" ? "es-MX" : "en-US";
}

type Params = Record<string, string | number>;

function format(text: string, params?: Params): string {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

/** Texto traducido con interpolación `{nombre}`. */
export function t(key: Key, params?: Params): string {
  return format(dictionaries[i18n.lang][key] ?? en[key] ?? key, params);
}

type PluralBase<K> = K extends `${infer B}.one` ? B : never;
export type PluralKey = PluralBase<Key>;

/** Texto con plural (`<clave>.one` / `<clave>.other`); `{count}` queda disponible. */
export function tn(key: PluralKey, count: number, params?: Params): string {
  const k = (count === 1 ? `${key}.one` : `${key}.other`) as Key;
  return t(k, { count, ...params });
}

/** Etiquetas predeterminadas del otro hablante en todos los idiomas (para resaltarlo). */
export function isOtherPartyLabel(name: string | null | undefined): boolean {
  return !!name && (name === en["record.otherParty"] || name === es["record.otherParty"]);
}
